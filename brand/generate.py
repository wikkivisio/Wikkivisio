"""Build Wikkivisio brand assets from the Fraunces W and wordmark.

Run from the repo root: python3 brand/generate.py
"""

from __future__ import annotations

from io import BytesIO
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "node_modules/@fontsource-variable/fraunces/files/fraunces-latin-opsz-normal.woff2"
OUT = ROOT / "brand"

SPRUCE = "#0e261f"
LIME = "#def56b"
INK = "#14241e"
PAPER = "#f4f0e6"
WORD = "Wikkivisio"


def instance(wght: float, opsz: float = 144):
    font = TTFont(FONT)
    inst = instantiateVariableFont(font, {"opsz": opsz, "wght": wght}, inplace=False)
    inst.flavor = None
    return inst


def glyph_path(inst: TTFont, char: str) -> str:
    glyph_set = inst.getGlyphSet()
    name = inst.getBestCmap()[ord(char)]
    pen = SVGPathPen(glyph_set)
    glyph_set[name].draw(pen)
    return pen.getCommands()


def glyph_bounds(inst: TTFont, char: str) -> tuple[int, int, int, int]:
    glyf = inst["glyf"][inst.getBestCmap()[ord(char)]]
    return glyf.xMin, glyf.yMin, glyf.xMax, glyf.yMax


def shape(inst: TTFont, text: str, tracking: float) -> list[tuple[str, int, int]]:
    data = BytesIO()
    inst.save(data)
    face = hb.Face(data.getvalue())
    font = hb.Font(face)
    buffer = hb.Buffer()
    buffer.add_str(text)
    buffer.guess_segment_properties()
    hb.shape(font, buffer)
    placed: list[tuple[str, int, int]] = []
    x = 0
    for info, pos in zip(buffer.glyph_infos, buffer.glyph_positions):
        char = text[info.cluster]
        placed.append((char, x + pos.x_offset, 0))
        x += pos.x_advance + int(tracking)
    return placed


def mark_group(inst: TTFont, size: float, pad: float) -> str:
    """Lime W centered in a size×size box, padded for a circular crop."""
    x0, y0, x1, y1 = glyph_bounds(inst, "W")
    gw, gh = x1 - x0, y1 - y0
    scale = size * (1 - 2 * pad) / max(gw, gh)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    path = glyph_path(inst, "W")
    return (
        f'<g transform="translate({size / 2:.3f} {size / 2:.3f}) '
        f'scale({scale:.6f} {-scale:.6f}) translate({-cx:.3f} {-cy:.3f})">'
        f'<path d="{path}" fill="#def56b"/></g>'
    )


def badge(inst: TTFont, fill: str, glyph: str) -> str:
    group = mark_group(inst, 64, 0.2).replace('fill="#def56b"', f'fill="{glyph}"')
    return f'<g><circle cx="32" cy="32" r="32" fill="{fill}"/>{group}</g>'


def wordmark_paths(inst: TTFont, tracking: float) -> tuple[str, float, float]:
    placed = shape(inst, WORD, tracking)
    parts = []
    max_x = 0.0
    y_max = 0
    for char, x, _y in placed:
        x0, y0, x1, y1 = glyph_bounds(inst, char)
        y_max = max(y_max, y1)
        parts.append(f'<g transform="translate({x} 0)"><path d="{glyph_path(inst, char)}"/></g>')
        max_x = max(max_x, x + x1)
    return "".join(parts), max_x, y_max


def lockup(mark_fill: str, glyph_fill: str, word_fill: str) -> str:
    mark = instance(800)
    word = instance(560)
    text, text_width, cap = wordmark_paths(word, tracking=-50)
    scale = 78 / cap
    mark_size = 96
    gap = 22
    text_width_px = text_width * scale
    height = 112
    width = mark_size + gap + text_width_px + 4
    baseline = height / 2 + (cap * scale) / 2
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width:.2f} {height}" role="img" aria-label="Wikkivisio">
  <title>Wikkivisio</title>
  <g transform="translate(0 {(height - mark_size) / 2:.2f}) scale({mark_size / 64:.4f})">
    {badge(mark, mark_fill, glyph_fill)}
  </g>
  <g fill="{word_fill}" transform="translate({mark_size + gap:.2f} {baseline:.2f}) scale({scale:.6f} {-scale:.6f})">
    {text}
  </g>
</svg>
'''


def profile_svg() -> str:
    mark = instance(800)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" role="img" aria-label="Wikkivisio">
  <title>Wikkivisio</title>
  <rect width="1024" height="1024" fill="{SPRUCE}"/>
  {mark_group(mark, 1024, 0.19)}
</svg>
'''


def favicon_svg() -> str:
    mark = instance(800)
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" role="img" aria-label="Wikkivisio">
  <title>Wikkivisio</title>
  <rect width="64" height="64" fill="{SPRUCE}"/>
  {mark_group(mark, 64, 0.14)}
</svg>
'''


def react_mark() -> str:
    mark = instance(800)
    x0, y0, x1, y1 = glyph_bounds(mark, "W")
    gw, gh = x1 - x0, y1 - y0
    scale = 64 * (1 - 2 * 0.2) / max(gw, gh)
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    path = glyph_path(mark, "W")
    transform = f"translate(32 32) scale({scale:.6f} {-scale:.6f}) translate({-cx:.3f} {-cy:.3f})"
    return (
        "/** Fraunces display W. Regenerated by brand/generate.py */\n"
        f"export const markPath = {path!r}\n"
        f"export const markTransform = {transform!r}\n"
    )


def main() -> None:
    OUT.mkdir(exist_ok=True)
    (OUT / "mark.svg").write_text(profile_svg())
    (OUT / "logo.svg").write_text(lockup(SPRUCE, LIME, INK))
    (OUT / "logo-dark.svg").write_text(lockup(LIME, SPRUCE, PAPER))
    (OUT / "favicon.svg").write_text(favicon_svg())
    public = ROOT / "public"
    (public / "favicon.svg").write_text(favicon_svg())
    (public / "logo.svg").write_text(lockup(SPRUCE, LIME, INK))
    (ROOT / "src" / "brandMark.ts").write_text(react_mark())
    print("wrote svg")


if __name__ == "__main__":
    main()
